/// Current UI language. 'en' or 'ar'. Digits stay Latin in both.
String currentLang = 'en';

bool get isArabic => currentLang == 'ar';

String t(String key, [Map<String, String> vars = const {}]) {
  var s = (isArabic ? _ar[key] : null) ?? _en[key] ?? key;
  vars.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

